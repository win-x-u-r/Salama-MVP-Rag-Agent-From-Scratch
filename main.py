class AguiTimingMiddleware:
    """Times the /agui SSE stream: first event, first visible token, total.

    The endpoint handler is generated by ag_ui_langgraph, so timing hooks in
    at the ASGI layer by watching response chunks as they are sent.
    """

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http" or scope["path"] != "/agui":
            return await self.app(scope, receive, send)

        start = time.perf_counter()
        seen = {"first_event": False, "first_token": False}

        async def timed_send(message):
            if message["type"] == "http.response.body":
                now = time.perf_counter() - start
                body = message.get("body", b"")
                if body and not seen["first_event"]:
                    seen["first_event"] = True
                    logger.info(f"[timing][agui] first event: {now:.2f}s")
                if (
                    body
                    and not seen["first_token"]
                    and b"TEXT_MESSAGE_CONTENT" in body
                ):
                    seen["first_token"] = True
                    logger.info(f"[timing][agui] time-to-first-token: {now:.2f}s")
                if not message.get("more_body", False):
                    logger.info(f"[timing][agui] total request: {now:.2f}s")
            await send(message)

        await self.app(scope, receive, timed_send)


app.add_middleware(AguiTimingMiddleware)

